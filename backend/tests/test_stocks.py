async def test_stock_cache_coalesces_requests_and_marks_stale(tmp_path):
    service = StockService(tmp_path / 'quotes.sqlite3')
    count = 0

    async def provider(*args):
        nonlocal count
        count += 1
        await asyncio.sleep(.01)
        return {'rows':[{'symbol':'000001','name':'接口测试数据','price':10.0}], 'source':'测试接口'}

    service.worker = provider
    results = await asyncio.gather(service.get('quotes'), service.get('quotes'))
    assert count == 1 and all(r['status'] == 'ok' for r in results)
    assert results[0]['simulated'] is False  # Provider data is passed through, never generated by the cache.
    with sqlite3.connect(service.path) as db:
        db.execute('UPDATE stock_cache SET fetched=0')

    async def offline(*args):
        raise OSError('test offline')

    service.worker = offline
    stale = await service.get('quotes')
    assert stale['status'] == 'stale' and stale['stale'] and stale['error']
    assert stale['rows'] == results[0]['rows'] and stale['fetched_at'] == '1970-01-01T08:00:00+08:00'
    missing = await service.get('history','600000')
    assert missing['status'] == 'unavailable' and not missing['rows'] and missing['fetched_at'] is None


async def test_public_readonly_stock_routes_keep_bank_private(settings):
    settings.app_auth_enabled = True
    bank = create_app(settings)
    async with bank.router.lifespan_context(bank), httpx.AsyncClient(transport=httpx.ASGITransport(app=bank), base_url='http://127.0.0.1:8000') as client:
        assert (await client.get('/api/bank')).status_code == 401
        assert (await client.get('/api/stocks/catalog')).status_code in {401,404}
    app = create_stock_app(settings.database_path.parent / 'independent-market.sqlite3')

    async def provider(operation, symbol='', adjust=''):
        if operation == 'quotes':
            return {'rows':[{'symbol':'000001','name':'接口测试数据','price':10.0}], 'source':'测试接口'}
        return {'symbol':symbol,'rows':[{'date':'2026-10-14','open':10,'close':11,'high':12,'low':9,'volume':1000,'amount':10000,'change_percent':10}], 'source':'测试接口', 'adjust':adjust or 'none'}

    route_service = app.state.stock_service
    route_service.path = StockService(settings.database_path.parent / 'market.sqlite3').path
    route_service.worker = provider
    async with app.router.lifespan_context(app), httpx.AsyncClient(transport=httpx.ASGITransport(app=app), base_url='http://127.0.0.1:8000') as c:
        assert (await c.get('/api/bank')).status_code == 404
        assert (await c.get('/api/stocks/catalog?q=平安')).json()['items'][0]['symbol'] == '000001'
        assert (await c.get('/api/stocks/quotes?q=000001')).json()['total'] == 1
        assert (await c.get('/api/stocks/000001/history')).json()['rows'][0]['close'] == 11
        assert (await c.get('/api/stocks/not-a-symbol/history')).status_code == 422
        assert (await c.get('/api/stocks/000001/history?days=999999')).status_code == 422
        assert (await c.get('/api/stocks/000001/history?adjust=hfq')).status_code == 422
        assert (await c.post('/api/stocks/orders',json={'symbol':'000001'})).status_code in {404,405}


def test_tencent_volume_normalization_and_missing_prices(monkeypatch):
    def unavailable(**kwargs):
        raise ValueError('test provider unavailable')

    records = [{'date':'2026-10-14','open':10,'close':10,'high':11,'low':9,'volume':100,'amount':100000}]
    frame = SimpleNamespace(to_dict=lambda *args: records)
    monkeypatch.setitem(sys.modules,'akshare',SimpleNamespace(stock_zh_a_hist=unavailable,stock_zh_a_hist_tx=lambda **kwargs: frame))
    result = run('history','000001','')
    assert result['rows'][0]['volume'] == 10000
    assert result['source'] == 'AKShare · 腾讯证券'
    records[0]['volume'] = 10000
    assert run('history','000001','')['rows'][0]['volume'] == 10000
